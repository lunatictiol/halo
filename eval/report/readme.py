"""Regenerate the results block of README.md from results/*.json. Every number in that block is read from a file.

    uv run python -m eval.report.readme

Text outside the <!-- results:start --> / <!-- results:end --> markers is hand-written and left untouched.
"""

import json
import re

from eval.report.m4_report import abstentions, rescues
from eval.report.summary import ABSTENTION_SPLIT, ANSWERABLE_SPLIT
from eval.results import RESULTS_DIR
from halo.config import ROOT

README = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"
FINAL, FULL_SPLIT = "m6_graph", "full"
# (stage, run name, what changed). All on dev_sample's 303 questions; M1-M5 on the 100-paper dev index.
STAGES = [("M2 baseline", "m2_baseline", "dense top-5 → answer"),
          ("M3 hybrid", "m3_retrieval_hybrid", "+ BM25, RRF fusion (retrieval only)"),
          ("M3 rerank", "m3_hybrid_rerank", "+ cross-encoder rerank"),
          ("M4 loop", "m4_graph_v2", "+ grade → rewrite → retry, abstain"),
          ("M5 grounded", "m5_check_v2", "+ citations, grounding check"),
          ("M6 full corpus", FINAL, "same pipeline, 980-paper index")]
COLS = ["R@5", "MRR", "Correct", "Correct (text)", "Faithful", "False-abst", "Abstention ↑", "Cite valid",
        "Median s/q"]
SLICES = [("overall", "overall", None),
          *[(f"type: {k}", "by_type", k) for k in ("extractive", "abstractive")],
          *[(f"modality: {k}", "by_modality", k) for k in ("text", "text-image", "text-table", "text-table-image")]]


def load(run: str, split: str) -> dict | None:
    p = RESULTS_DIR / f"{run}_{split}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def cell(res: dict | None, metric: str, block: str = "overall", key: str | None = None) -> dict:
    if res is None:
        return {}
    b = res["metrics"][block] if key is None else res["metrics"][block].get(key, {})
    return b.get(metric, {})


def mean(res: dict | None, metric: str, block: str = "overall", key: str | None = None) -> str:
    x = cell(res, metric, block, key).get("mean")
    return "–" if x is None else f"{x:.3f}"


def latency_s(res: dict) -> str:
    if res.get("graph"):
        return f"{res['graph']['graph_ms_median'] / 1000:.1f}"
    if "latency_ms_median" not in res:
        return "–"
    # Single pipeline: sum of per-stage medians (approximation; the stages are not timed end-to-end).
    lat = res["latency_ms_median"]
    return f"{(lat['retrieve'] + lat['generate']) / 1000:.1f}"


def row(stage: str, run: str, what: str, ans: dict | None, ab: dict | None) -> str:
    if ans is None:
        return f"| {stage} | {what} | `{run}` | " + " | ".join(["pending"] * len(COLS)) + " |"
    cells = [mean(ans, "recall@5"), mean(ans, "mrr"), mean(ans, "correct"),
             mean(ans, "correct", "by_modality", "text"), mean(ans, "faithful"), mean(ans, "abstained"),
             mean(ab, "abstained"), mean(ans, "citation_validity"), latency_s(ans)]
    return f"| {stage} | {what} | [`{run}`](results/{run}_{ANSWERABLE_SPLIT}.json) | " + " | ".join(cells) + " |"


def progression() -> list[str]:
    lines = ["| Stage | Change | Run | " + " | ".join(COLS) + " |", "|---" * (len(COLS) + 3) + "|"]
    return lines + [row(s, r, w, load(r, ANSWERABLE_SPLIT), load(r, ABSTENTION_SPLIT)) for s, r, w in STAGES]


def scale_table() -> list[str]:
    """Same pipeline: dev index vs full index on the same questions, then the whole answerable split."""
    dev, full_dev, full = (load("m5_check_v2", ANSWERABLE_SPLIT), load(FINAL, ANSWERABLE_SPLIT),
                           load(FINAL, FULL_SPLIT))
    runs = [("Dev index, dev_sample", dev), ("Full index, dev_sample", full_dev), ("Full index, full", full)]
    lines = ["| Slice | n dev_sample | n full | " + " | ".join(f"{n}: R@5 | {n}: Correct" for n, _ in runs) + " |",
             "|---" * (2 * len(runs) + 3) + "|"]
    for label, block, key in SLICES:
        ns = [cell(r, "correct", block, key).get("n", "–") for r in (dev, full)]
        cells = [f"{mean(r, 'recall@5', block, key)} | {mean(r, 'correct', block, key)}" for _, r in runs]
        lines.append(f"| {label} | {ns[0]} | {ns[1]} | " + " | ".join(cells) + " |")
    ab_dev, ab_full = load("m5_check_v2", ABSTENTION_SPLIT), load(FINAL, ABSTENTION_SPLIT)
    lines += ["", f"Abstention rate on `{ABSTENTION_SPLIT}`: dev index {mean(ab_dev, 'abstained')}, "
              f"full index {mean(ab_full, 'abstained')}. Sources: "
              f"[`m5_check_v2_*`](results/), [`{FINAL}_*`](results/)."]
    return lines


def block() -> str:
    loop, loop_ab = load("m4_graph_v2", ANSWERABLE_SPLIT), load("m4_graph_v2", ABSTENTION_SPLIT)
    n_rescued, rescued = rescues(loop)
    return "\n".join([
        START, "",
        "<!-- Generated by `uv run python -m eval.report.readme`; do not edit by hand. -->", "",
        f"### Progression on `{ANSWERABLE_SPLIT}` (303 answerable questions)", "",
        *progression(), "",
        f"Correct = LLM-judged correct vs the reference (a refusal counts as wrong). Faithful = answered questions "
        f"judged supported by the retrieved context. False-abst = answerable questions refused. Abstention ↑ = "
        f"share of `{ABSTENTION_SPLIT}` (152 questions whose papers are never indexed) correctly refused. "
        f"Cite valid = generator citations whose passages support their sentence. R@5 and MRR are against the "
        f"single gold section, on the top-5 the answer was generated from. Judge and generator are both "
        f"`qwen3:8b`.", "",
        "### Scaling to the full corpus", "",
        *scale_table(), "",
        "### Examples", "",
        f"<details><summary>Rewrite loop rescued a failed first retrieval ({n_rescued} on <code>{ANSWERABLE_SPLIT}"
        f"</code>, 5 shown, from <code>m4_graph_v2</code>)</summary>", "", *rescued, "</details>", "",
        f"<details><summary>Correct abstentions on <code>{ABSTENTION_SPLIT}</code> (5 shown, from "
        f"<code>m4_graph_v2</code>)</summary>", "", *abstentions(loop_ab), "</details>", "",
        END])


def main() -> None:
    text = README.read_text(encoding="utf-8")
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.DOTALL)
    if not pattern.search(text):
        raise SystemExit(f"README.md has no {START} ... {END} block")
    README.write_text(pattern.sub(lambda _: block(), text), encoding="utf-8")
    print(f"updated {README}")


if __name__ == "__main__":
    main()
