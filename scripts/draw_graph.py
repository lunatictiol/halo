"""Save the graph diagram (M4 loop + M5 verify node), generated from the compiled graph definition, as Mermaid (renders on GitHub).

    uv run python scripts/draw_graph.py        # -> docs/m5_graph.md
"""

from halo.config import ROOT, load_config
from halo.graph.pipeline import NODES, build_graph


def main() -> None:
    cfg = load_config()
    # The topology does not depend on what the nodes do, so stubs avoid loading models.
    graph = build_graph({n: lambda s: ({}, {}) for n in NODES}, cfg["graph"]["max_retries"])
    out = ROOT / "docs" / "m5_graph.md"
    out.write_text("# M5 graph: corrective loop + grounding check\n\nGenerated by `scripts/draw_graph.py` from "
                   "`halo/graph/pipeline.py`. `grade` routes to `rewrite` while retries remain (max_retries = "
                   f"{cfg['graph']['max_retries']}), otherwise to `abstain`. `verify` is the M5 grounding check "
                   "(D32).\n\n```mermaid\n" + graph.get_graph().draw_mermaid() + "```\n",
                   encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
